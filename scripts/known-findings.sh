#!/usr/bin/env bash
# Known findings: reproductions of the independent review against the CURRENT code, kept apart from the attack gallery counts.
# Usage: scripts/known-findings.sh [--skip-build]
# Writes evidence/attack-gallery/known-findings.json and docs/KNOWN-FINDINGS.md. Exit 1 while any finding is EXPLOITABLE (never forced green).
# After the fix branches merge, the same tests are the regression run: EXPLOITABLE flips to NOT_EXPLOITABLE.
set -euo pipefail
cd "$(dirname "$0")/.."
[ "${1:-}" = "--skip-build" ] || [ -f target/near/kruxa_instant_contract/kruxa_instant_contract.wasm ] || ./scripts/instant-build.sh
root=evidence/attack-gallery; out="$root/known-findings/records"; rm -rf "$out"; mkdir -p "$out"
set +e
KRUXA_FINDINGS_OUT="$PWD/$out" cargo test -p kruxa-tests --test known_findings -- --test-threads=2 >"$root/known-findings/run.log" 2>&1
rc=$?
set -e
python3 - "$out" "$rc" <<'PY'
import glob, json, os, subprocess, sys, datetime
out, rc = sys.argv[1:3]
recs = [json.load(open(p)) for p in sorted(glob.glob(out + "/*.json"))]
c = lambda r: sum(1 for x in recs if x["result"] == r)
head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
obj = {"schema": "kruxa.known-findings/1", "network": "SANDBOX", "git_head": head, "generated_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
       "counts": {"total": len(recs), "exploitable": c("EXPLOITABLE"), "not_exploitable": c("NOT_EXPLOITABLE"), "not_reproduced": c("NOT_REPRODUCED")},
       "cargo_exit": int(rc), "findings": recs}
json.dump(obj, open("evidence/attack-gallery/known-findings.json", "w"), indent=2)
df_path = "evidence/attack-gallery/disclosed-facts.json"
df = json.load(open(df_path)) if os.path.exists(df_path) else []
df_rows = "\n".join(f"| {x['id']} | {x['review']} | {x['title']} | {x['status']} | {x['summary'].replace('|', '/')} |" for x in df)
df_text = "" if not df else f"""
## Disclosed bounds and read-only facts (not reproductions, not counted above)

Measured or read once and written to `{df_path}`. The N-04 measurement is a sandbox test (`tests/tests/instant_token_leg_storage.rs`,
record in `evidence/instant-n04/`); the N-06 facts are read-only mainnet RPC view calls (no key, no write).

| Id | Review | Topic | Status | What was measured |
|---|---|---|---|---|
{df_rows}
"""
rows = "\n".join(f"| {x['id']} | {x['review_id']} | {x['title']} | **{x['result']}** | {x['summary'].replace('|', '/')} |" for x in recs)
open("docs/KNOWN-FINDINGS.md", "w").write(f"""# Known findings (pre-fix evidence)

Generated by `scripts/known-findings.sh` on git `{head[:12]}` from `evidence/attack-gallery/known-findings.json`. Do not edit by hand.
Source: the independent review REVIEW-INSTANT-LAUNCH.md. Each row is a reproduction against the CURRENT code in the near-workspaces sandbox.
These results are kept apart from the attack gallery counts and are never forced green.

EXPLOITABLE = the weakness reproduced today. NOT_EXPLOITABLE = it did not reproduce (after a fix this is the regression result).
NOT_REPRODUCED = the harness cannot exercise it (the summary says why).

{obj['counts']['exploitable']} exploitable, {obj['counts']['not_exploitable']} not exploitable, {obj['counts']['not_reproduced']} not reproduced.

| Id | Review | Finding | Result | What was measured |
|---|---|---|---|---|
{rows}

{df_text}
`make known-findings` exits 1 while any row is EXPLOITABLE.
""")
print(f"KNOWN FINDINGS: {obj['counts']}")
for x in recs:
    print(f"  {x['id']} {x['result']}: {x['summary'][:140]}")
sys.exit(1 if obj["counts"]["exploitable"] else 0)
PY
